/**
 * Get a random challenge for a specific scenario and phase
 */
export function getRandomChallenge(
  scenarioId: string,
  phaseNumber: number
): PredefinedChallenge {
  const challenges = PREDEFINED_CHALLENGES[scenarioId]?.[phaseNumber];
  if (!challenges || challenges.length === 0) {
    throw new Error(
      `No challenges found for scenario ${scenarioId} phase ${phaseNumber}`
    );
  }
  const randomIndex = Math.floor(Math.random() * challenges.length);
  return challenges[randomIndex];
}
